#!/usr/bin/env node
// Regenerates packages/cloudflare/src/ranges.ts from Cloudflare's published egress endpoints.
//
// The vendored module is fs-cloudflare's allowlist: every request the gate admits is admitted
// because its address sits in one of these ranges. So this script refuses to write anything it
// cannot fully validate — a truncated body, an HTML error page, or a single malformed entry
// aborts with a non-zero exit and leaves the vendored file untouched. A wrong write here either
// opens the gate to the whole internet or 403s every real visitor.
//
// The snapshot date in the header is only rewritten when the ranges themselves change, so
// re-running against unchanged endpoints leaves the file byte-identical. That is what makes
// `git diff --exit-code` a usable drift signal for .github/workflows/cf-ranges-drift.yml.

import {readFileSync, writeFileSync} from 'node:fs';
import path from 'node:path';

const TARGET = path.join(import.meta.dirname, '..', 'packages', 'cloudflare', 'src', 'ranges.ts');

const SOURCES = [
    {name: 'CLOUDFLARE_IPV4', url: 'https://www.cloudflare.com/ips-v4', pattern: /^\d{1,3}(\.\d{1,3}){3}\/\d{1,2}$/},
    {name: 'CLOUDFLARE_IPV6', url: 'https://www.cloudflare.com/ips-v6', pattern: /^[\da-f:]+\/\d{1,3}$/},
];

async function fetchRanges({url, pattern}) {
    const response = await fetch(url);
    if (!response.ok) {
        throw new Error(`${url} responded ${response.status} ${response.statusText}`);
    }

    const body = await response.text();
    const ranges = body
        .split('\n')
        .map((line) => line.trim())
        .filter((line) => line.length > 0);

    if (ranges.length === 0) {
        throw new Error(`${url} returned no ranges`);
    }

    const malformed = ranges.filter((range) => !pattern.test(range));
    if (malformed.length > 0) {
        throw new Error(
            `${url} returned ${malformed.length} entries that are not CIDR ranges: ${malformed.join(', ')}`,
        );
    }

    return ranges;
}

function renderArray(name, ranges) {
    return `export const ${name} = [\n${ranges.map((range) => `    '${range}',`).join('\n')}\n];\n`;
}

function render(rendered, snapshot) {
    return (
        [
            `// Cloudflare's published egress ranges, source https://www.cloudflare.com/ips/ (snapshot ${snapshot}).`,
            '// Generated by scripts/update-cf-ranges.mjs — do not hand-edit. The scheduled cf-ranges-drift',
            '// workflow re-runs that script weekly and fails when the live endpoints no longer match.',
            '',
        ].join('\n') + rendered.join('\n')
    );
}

// The date is the only part of the file that is not a function of the endpoints; ignore it when
// deciding whether anything actually changed.
function withoutSnapshotDate(source) {
    return source.replace(/\(snapshot \d{4}-\d{2}-\d{2}\)/, '(snapshot)');
}

async function main() {
    const arrays = [];
    for (const source of SOURCES) {
        arrays.push(renderArray(source.name, await fetchRanges(source)));
    }

    const current = readFileSync(TARGET, 'utf8');
    const next = render(arrays, new Date().toISOString().slice(0, 10));

    if (withoutSnapshotDate(current) === withoutSnapshotDate(next)) {
        process.stdout.write(
            `update-cf-ranges: ${path.relative(process.cwd(), TARGET)} already matches the live endpoints.\n`,
        );
        return;
    }

    writeFileSync(TARGET, next);
    process.stdout.write(
        `update-cf-ranges: rewrote ${path.relative(process.cwd(), TARGET)} — the live endpoints changed.\n`,
    );
}

await main();
